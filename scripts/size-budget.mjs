// Records each icon's size budget in packages/react/test/size-budget.json.
//
//   pnpm build && node scripts/size-budget.mjs
//
// Run it after a change that's meant to change sizes: new or redrawn icons
// from upstream, or a generator change you've checked. The size test then
// fails if any icon grows past its budget, so an accidental increase shows up
// in review as a failing test instead of in an app's bundle.

import { writeFile } from "node:fs/promises"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { ALLOWANCE, budgetFor, measureIconSizes } from "./lib/size.mjs"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const OUT = join(ROOT, "packages", "react", "test", "size-budget.json")

const budgets = (sizes) => Object.fromEntries(Object.entries(sizes).map(([name, bytes]) => [name, budgetFor(bytes)]))

const sizes = await measureIconSizes(join(ROOT, "packages", "react", "dist"))
const record = {
  $comment:
    "Generated by scripts/size-budget.mjs: each icon module's gzipped size after minifying, times the allowance. The size test fails if an icon goes over. Rerun after a deliberate size change.",
  allowance: ALLOWANCE,
  wrapper: budgetFor(sizes.wrapper),
  rounded: budgets(sizes.rounded),
  sharp: budgets(sizes.sharp),
}
await writeFile(OUT, `${JSON.stringify(record, null, 2)}\n`)

const values = Object.values(sizes.rounded).sort((a, b) => a - b)
const median = values[values.length >> 1]
console.log(`Wrote ${values.length * 2} icon budgets to packages/react/test/size-budget.json (rounded median ${median} B gzipped, wrapper ${sizes.wrapper} B)`)
