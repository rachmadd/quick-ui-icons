const WIDTH = 100

/** What quick-ui's <Icon> wrapper sets; a drawing only states where it differs. */
const WRAPPER_PAINT = {
  fill: "none",
  stroke: "currentColor",
  "stroke-width": "2",
  "stroke-linecap": "round",
  "stroke-linejoin": "round",
}
const STROKE_ONLY = new Set(["stroke-width", "stroke-linecap", "stroke-linejoin"])

